class RelevanceTest(unittest.TestCase):
    def test_protection_messages_pass(self):
        for text in RELEVANT:
            ok, hits = is_relevant(text)
            self.assertTrue(ok, f"missed: {text[:60]} score={score(text)[0]}")
            self.assertTrue(hits)

    def test_noise_is_dropped(self):
        for text in NOISE:
            ok, _ = is_relevant(text)
            self.assertFalse(ok, f"let through: {text[:60]} score={score(text)[0]}")

    def test_strict_keeps_the_digest(self):
        self.assertTrue(is_relevant(DIGEST, "strict")[0])

    def test_off_keeps_everything(self):
        self.assertTrue(is_relevant("Дякую!", "off")[0])


if __name__ == "__main__":
    unittest.main()
